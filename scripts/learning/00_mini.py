#!/usr/bin/env python3
"""最小最小版：一个特征、一个公式、一个预测。

别看上一个脚本了，先看这个。全部代码只有 30 行，
而且没有函数、没有类、没有抽象 —— 从上到下读一遍就能懂。

要理解的三件事：
    1. 特征是什么     = 今天能看到的数字
    2. 标签是什么     = 未来才会发生的答案
    3. 学习是什么     = 找一条直线，让 f(特征) 尽量接近标签
"""
import duckdb
import numpy as np

# ---------------------------------------------------------------
# 第 1 步：取数据
# ---------------------------------------------------------------
# 我们要两列：
#   rsi_14              —— 特征（今天就能算出来）
#   future_return_5d    —— 标签（5 天后才知道）
con = duckdb.connect()
df = con.execute("""
    SELECT time, rsi_14, future_return_5d
    FROM read_parquet('/opt/quantmind/data/quantdb/6_ml_datasets/features_daily/*/data.parquet')
    WHERE time >= DATE '2022-01-01' AND rsi_14 IS NOT NULL
""").df()

print(f"拿到 {len(df):,} 行数据")
print(df.head(3).to_string(index=False))

# ---------------------------------------------------------------
# 第 2 步：切成「过去」和「未来」
# ---------------------------------------------------------------
# 用 2025 年之前的数据学习，2025 年之后的数据检验。
# 这叫「样本内 / 样本外」。绝不能拿同一批数据既学又考。
df = df.dropna(subset=["rsi_14", "future_return_5d"])   # 去掉空值，否则后面算出来是 nan
past = df[df.time < "2025-01-01"]     # 训练集
future = df[df.time >= "2025-01-01"]  # 测试集

print(f"\n训练：{len(past):,} 行（2022 ~ 2024）")
print(f"测试：{len(future):,} 行（2025 ~ 2026）")

# ---------------------------------------------------------------
# 第 3 步：学习 —— 找一条直线
# ---------------------------------------------------------------
# 我们假设：     未来收益 ≈ a + b × RSI
# polyfit 就是解出 a 和 b，让这条直线尽量贴近所有历史数据点。
# 「训练模型」这四个字，在这里就是这一行。
b, a = np.polyfit(past.rsi_14, past.future_return_5d, 1)
print(f"\n学到的公式：未来5日收益 ≈ {a:.4f} + {b:.6f} × RSI")

# ---------------------------------------------------------------
# 第 4 步：预测
# ---------------------------------------------------------------
# 把公式套到「没见过」的测试数据上。公式没变，数据是新的。
future = future.assign(pred=a + b * future.rsi_14).dropna(subset=["pred", "future_return_5d"])

# ---------------------------------------------------------------
# 第 5 步：打分 —— 用相关系数
# ---------------------------------------------------------------
# corr 越接近 1，说明预测和真实越一致；接近 0 说明毫无关系。
# 这个相关系数，在量化里有个专门名字：IC（信息系数）。
ic_in = np.corrcoef(a + b * past.rsi_14, past.future_return_5d)[0, 1]
ic_out = np.corrcoef(future.pred, future.future_return_5d)[0, 1]

print(f"\n训练集上的 IC：{ic_in:+.4f}   ← 看起来多好")
print(f"测试集上的 IC：{ic_out:+.4f}   ← 真实水平")
print(f"差距：{ic_in - ic_out:+.4f}       ← 这个差距就是「过拟合」")
