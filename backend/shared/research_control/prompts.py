SLOT_TITLES: dict[str, str] = {
    "midday": "午间复盘",
    "close": "收盘复盘",
    "inference": "推理数据复盘",
    "news": "新闻复盘",
    "night": "夜间综合总结",
}


def build_system_prompt() -> str:
    return SYSTEM_PROMPT


def build_user_prompt(
    slot: str,
    dossier: Dossier,
    *,
    prior_brief: str = "",
    extra: str = "",
) -> str:
    """拼装一档的 user 消息：任务 → 事实包 → 已有 brief → 输出契约。"""
    task = SLOT_TASKS.get(slot) or SLOT_TASKS["close"]
    parts = [
        f"【档位】{SLOT_TITLES.get(slot, slot)}｜复盘日 {_dash(dossier.day)}｜"
        f"目标交易日 {_dash(dossier.target)}｜当前北京时间 "
        f"{dossier.now.strftime('%Y-%m-%d %H:%M')}",
        task,
        dossier.render(),
    ]
    if prior_brief.strip():
        parts.append(
            "## 开盘前已有的总控 brief（供对照，不要照抄）\n" + prior_brief.strip()
        )
    if extra.strip():
        parts.append("## 本档补充输入\n" + extra.strip())
    parts.append(MACHINE_CONTRACT)
    return "\n\n".join(parts)
